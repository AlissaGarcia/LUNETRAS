-- 1. LIMPEZA
DROP TABLE IF EXISTS avaliacoes_psicogeneticas CASCADE;
DROP TABLE IF EXISTS alunos CASCADE;
DROP TABLE DROP TABLE IF EXISTS turmas CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

-- 2. TABELAS PRINCIPAIS

-- Tabela de Usuários (Administradores e Professores)
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(50) NOT NULL CHECK (perfil IN ('ADMIN', 'PROFESSOR')),
    ativo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_usuarios_email ON usuarios(email);
CREATE INDEX idx_usuarios_perfil ON usuarios(perfil);

-- Tabela de Turmas (Classes)
CREATE TABLE turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    ano INTEGER NOT NULL CHECK (ano BETWEEN 1 AND 5),
    turno VARCHAR(50) NOT NULL CHECK (turno IN ('MANHA', 'TARDE', 'INTEGRAL')),
    professor_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    ativa BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_turmas_professor_id ON turmas(professor_id);
CREATE INDEX idx_turmas_ativa ON turmas(ativa);

-- Tabela de Alunos
CREATE TABLE alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    data_nascimento DATE NOT NULL,
    turma_id BIGINT NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
    nivel VARCHAR(50) DEFAULT 'SEM_DADOS' CHECK (nivel IN ('SEM_DADOS', 'ICONICA', 'GARATUJA', 'PRE_SILABICO', 'SILABICO_SEM_VALOR_SONORO', 'SILABICO_COM_VALOR_SONORO', 'ALFABETICO', 'ORTOGRAFICO')),
    status VARCHAR(50) DEFAULT 'SEM_AVALIACAO' CHECK (status IN ('SEM_AVALIACAO', 'AVALIADO', 'REAVALIAR')),
    observacoes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_alunos_turma_id ON alunos(turma_id);
CREATE INDEX idx_alunos_email ON alunos(email);
CREATE INDEX idx_alunos_nivel ON alunos(nivel);

-- Tabela de Avaliações Psicogenéticas
CREATE TABLE avaliacoes_psicogeneticas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL REFERENCES alunos(id) ON DELETE CASCADE,
    professor_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    bimestre INTEGER NOT NULL CHECK (bimestre BETWEEN 1 AND 4),
    nivel VARCHAR(50) NOT NULL CHECK (
        nivel IN (
            'SEM_DADOS',
            'ICONICA',
            'GARATUJA',
            'PRE_SILABICO',
            'SILABICO_SEM_VALOR_SONORO',
            'SILABICO_COM_VALOR_SONORO',
            'ALFABETICO',
            'ORTOGRAFICO'
        )
    ),
    status VARCHAR(50) DEFAULT 'SEM_AVALIACAO' CHECK (
        status IN ('SEM_AVALIACAO', 'AVALIADO', 'REAVALIAR')
    ),
    observacoes TEXT,
    data_avaliacao DATE NOT NULL,
    periodo_letivo INTEGER NOT NULL DEFAULT 2026,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_avaliacoes_aluno ON avaliacoes_psicogeneticas(aluno_id);
CREATE INDEX idx_avaliacoes_professor ON avaliacoes_psicogeneticas(professor_id);
CREATE INDEX idx_avaliacoes_nivel ON avaliacoes_psicogeneticas(nivel);
CREATE INDEX idx_avaliacoes_bimestre ON avaliacoes_psicogeneticas(bimestre, periodo_letivo);
CREATE UNIQUE INDEX uk_avaliacoes_unique_bimestre 
    ON avaliacoes_psicogeneticas(aluno_id, bimestre, periodo_letivo);

